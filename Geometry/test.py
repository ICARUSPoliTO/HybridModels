def is_between(value, a, b):
    """
    Support function for checking if a value is between a and b
    :param value: value to check
    :param a: first side
    :param b: second side
    :return: Boolean
    """
    start = min([a, b])
    end = max([a, b])

    result = (value >= start and value <= end)
    return result


def create_regular_poligon(n_sides, circum_radius):
    """
    Generates a regular poligon inscripted in the circumference.
    :param n_sides: Number of sides
    :param circum_radius: Radius of circumscribed circonference
    :return: x_poly, y_poly
    """
    theta = 2 * np.pi / n_sides
    thetas = np.arange(0, n_sides, 1)
    thetas = thetas * theta
    x_poly = circum_radius * np.cos(thetas)
    y_poly = circum_radius * np.sin(thetas)
    return x_poly, y_poly


def create_repeated_instance(x, y, n_instances):
    """
    Given the points, repeats an instance around the origin for the given number.
    It also removes the points sharing the same location.
    :param x: x-axis points
    :param y: y-axis points
    :param n_instances: number of instances to repeat
    :return: x_u, y_u
    """
    theta = 2 * np.pi / n_instances
    thetas = np.arange(0, n_instances, 1) * theta

    angles = np.arctan2(y, x)
    radius = np.hypot(x, y)

    angles_rep = []
    radius_rep = []
    for i in range(n_instances):
        angles_rep.append(thetas[i] + angles)
        radius_rep.append(radius)

    angles_rep = np.array(angles_rep).ravel()
    radius_rep = np.array(radius_rep).ravel()

    x_rep = radius_rep * np.cos(angles_rep)
    y_rep = radius_rep * np.sin(angles_rep)

    pts = np.vstack((x_rep, y_rep)).T
    _, idx = np.unique(pts, axis=0, return_index=True)
    idx_sorted = np.sort(idx)
    pts_unique_in_order = pts[idx_sorted]
    x_u, y_u = pts_unique_in_order[:, 0], pts_unique_in_order[:, 1]

    return x_u, y_u


def translate_figure(x, y):
    """
    This function is used to translate the figure coordinates to have the origin inside it.
    :param x: np.array of x values
    :param y: np.array of y values
    :return: x_translated, y_translated
    """
    xG = np.sum(x) / np.size(x)
    yG = np.sum(y) / np.size(y)

    x_translated = x - xG
    y_translated = y - yG
    return x_translated, y_translated


def sort_input(x, y, z=1):
    """
    This function sorts the (x, y) inputs to be couterclock-wise or clock-wise depending on z.
    Use it carefully because it may change the desired geometry.
    :param x: np.array of x values
    :param y: np.array of y values
    :param z: z=1 counterclock, z=-1 clockwise
    :return: x_sorted, y_sorted
    """
    thetas = np.atan2(y, x)
    thetas[thetas < 0] += 2 * np.pi

    thetas = thetas * z
    sorted_indices = np.argsort(thetas)
    x_sorted = x[sorted_indices]
    y_sorted = y[sorted_indices]
    return x_sorted, y_sorted


def fill_borders(x, y, n_points_per_side):
    """
    Linear fill between (x, y) points.
    :param x: x-axis points
    :param y: y-axis points
    :param n_points_per_side: number of points between every x and y
    :return: x_fill, y_fill
    """
    x2 = np.r_[x, x[0]]
    y2 = np.r_[y, y[0]]

    x1 = x2[1:]
    y1 = y2[1:]

    t = np.linspace(0, 1, n_points_per_side + 1)[:-1]
    dx = (x1 - x)[:, None]  # (N,1)
    dy = (y1 - y)[:, None]  # (N,1)
    xs = x[:, None] + dx * t[None, :]  # (N,k)
    ys = y[:, None] + dy * t[None, :]  # (N,k)

    x_fill = xs.ravel()
    y_fill = ys.ravel()

    return x_fill, y_fill


def fill_borders_circumference(x, y, n_points_per_side, tol = 1e-6):
    """
    Circular fill between (x, y) points if they have the same radius, or linear fill otherwise.
    :param x: x-axis points
    :param y: y-axis points
    :param n_points_per_side: number of points between every x and y
    :return: x_fill, y_fill
    """
    if np.asarray(x).size > 1:
        x2 = np.r_[x, x[0]]
        y2 = np.r_[y, y[0]]

        x0 = x2[:-1]
        y0 = y2[:-1]
        x1 = x2[1:]
        y1 = y2[1:]

        t = np.linspace(0, 1, n_points_per_side + 1)[:-1]
        dx = (x1 - x)[:, None]  # (N,1)
        dy = (y1 - y)[:, None]  # (N,1)

        r0 = np.hypot(x0, y0)
        r1 = np.hypot(x1, y1)
        same_r = np.isclose(r0, r1, atol=tol)

        theta0 = np.arctan2(y0, x0)  # (-pi, pi]
        theta1 = np.arctan2(y1, x1)
        delta = theta1 - theta0
        delta = (delta + np.pi) % (2.0 * np.pi) - np.pi

        t_row = t[None, :]  # (1,k)

        xs_lin = x0[:, None] + dx * t_row
        ys_lin = y0[:, None] + dy * t_row

        r0_col = r0[:, None]
        theta0_col = theta0[:, None]
        delta_col = delta[:, None]
        thetas = theta0_col + delta_col * t_row  # (N,k)
        xs_circ = r0_col * np.cos(thetas)
        ys_circ = r0_col * np.sin(thetas)

        mask = same_r[:, None]  # (N,1) broadcastable
        xs_block = np.where(mask, xs_circ, xs_lin)
        ys_block = np.where(mask, ys_circ, ys_lin)

        x_fill = xs_block.ravel()
        y_fill = ys_block.ravel()
    else:
        r = np.hypot(x, y)
        thetas = t = np.linspace(0, 1, n_points_per_side + 1)[:-1] * 2 * np.pi
        x_fill = r * np.cos(thetas)
        y_fill = r * np.sin(thetas)

    return x_fill, y_fill


def calculate_surfaces_from_points(x, y, lc, step=0.0):
    """
    This function calculates port area and burning area of a fuel grain, given the section points and the length.
    If step is different from zero, it calculates the burning area of a swirled grain.
    Burning area calculation has some uncertainties, an efficiency based on observations was developed.
    :param x: np.array of x values [m]
    :param y: np.array of y values [m]
    :param lc: Grain length [m]
    :param step: Helix step [m]
    :return: Port_area [m^2], Burning_area [m^2]
    """

    r = np.hypot(x, y)

    x2 = np.r_[x, x[0]]
    y2 = np.r_[y, y[0]]
    r2 = np.r_[r, r[0]]

    dx = np.diff(x2)
    dy = np.diff(y2)

    a = r2[:-1]  # (a) side of the triangle formed by two points and the origin
    b = r2[1:]  # (b) side of the triangle formed by two points and the origin
    c = np.hypot(dx, dy)  # (c) side of the triangle formed by two points and the origin

    p = (a + b + c) / 2

    area_term = p * (p - a) * (p - b) * (p - c)
    area_term[area_term < 0] = 0.0
    areas = np.sqrt(area_term)  # Erone di Alessandria
    PortArea = np.sum(areas)

    perimeter = np.sum(c)
    if step == 0.0:
        BurningArea = perimeter * lc
    else:
        # Kerr = 0.2*0.1*2*np.pi/(0.96*16) # from observations
        # rend = 1 - Kerr * perimeter / step
        # Kerr = 0.2 * 0.1 / (2 * np.sqrt(2)) # from observations
        # rend = 1 - 0.908 * Kerr * np.max(r) / step
        # print(rend)

        h = min(np.min(c), step) / 10

        dtheta = h * 360 / step
        n_step = lc / h

        thetas = np.atan2(y, x) + np.deg2rad(dtheta)
        xT = r * np.cos(thetas)
        yT = r * np.sin(thetas)
        s = np.abs(dx * yT - dy * xT + dy * x - dx * y) / np.hypot(dx, dy)

        H = np.hypot(h, s)

        BurningArea = n_step * np.sum(H * c)

    return PortArea, BurningArea


# ---------- helper ----------
def remove_close_vertices(x, y, tol=1e-12):
    pts = np.column_stack((np.asarray(x, float), np.asarray(y, float)))
    if pts.shape[0] == 0:
        return np.array([]), np.array([])
    keep = [0]
    for i in range(1, pts.shape[0]):
        if np.hypot(*(pts[i] - pts[keep[-1]])) > tol:
            keep.append(i)
    pts2 = pts[keep]
    return pts2[:,0], pts2[:,1]

def remove_collinear_simple(x, y, tol=1e-12):
    """
    Rimuove punti collineari consecutivi (semplice passaggio).
    Mantiene ordine e chiusura logica.
    """
    x = np.asarray(x, dtype=float).ravel()
    y = np.asarray(y, dtype=float).ravel()
    if x.size < 3:
        return x.copy(), y.copy()
    # ensure closed indexing for checks
    N = x.size
    keep = []
    for i in range(N):
        im = (i-1) % N
        ip = (i+1) % N
        ux, uy = x[i] - x[im], y[i] - y[im]
        vx, vy = x[ip] - x[i], y[ip] - y[i]
        # cross product
        cross = ux * vy - uy * vx
        if abs(cross) > tol:
            keep.append(i)
    if len(keep) < 3:
        # fallback: return original if too aggressive
        return x, y
    x_new = x[keep]; y_new = y[keep]
    return x_new, y_new

def remove_samearc_simple(x, y, tol=1e-12):
    """
    Rimuove punti sullo stesso arco consecutivi (semplice passaggio).
    Mantiene ordine e chiusura logica.
    """
    x = np.asarray(x, dtype=float).ravel()
    y = np.asarray(y, dtype=float).ravel()
    if x.size < 3:
        return x.copy(), y.copy()
    # ensure closed indexing for checks
    N = x.size
    keep = []
    for i in range(N):
        im = (i-1) % N
        ip = (i+1) % N
        rm = np.hypot(x[im], y[im])
        r = np.hypot(x[i], y[i])
        rp = np.hypot(x[ip], y[ip])
        # cross product

        if not(np.isclose(r, rm, atol=tol) & np.isclose(r, rp, atol=tol)):
            keep.append(i)

    x_new = x[keep]; y_new = y[keep]
    if x_new.size < 3:
        try:
            x_new, y_new = x[0], y[0]
        except:
            x_new, y_new = x, y

    return x_new, y_new

def _line_intersection_from_dirs(pA, vA, pB, vB, eps=1e-12):
    """
    Solve pA + s*vA = pB + t*vB for s,t.
    Returns (ok, point, s, t, cond) where ok is True if solution accepted.
    """
    A = np.column_stack((vA, vB))   # 2x2
    b = pB - pA
    det = np.linalg.det(A)
    cond = np.linalg.cond(A) if np.isfinite(det) else np.inf
    if abs(det) < eps or cond > 1e12:
        # try least squares
        try:
            sol, *_ = np.linalg.lstsq(A, b, rcond=None)
            s, t = float(sol[0]), float(sol[1])
            pt = pA + s * vA
            return True, pt, s, t, cond
        except Exception:
            return False, None, None, None, cond
    else:
        sol = np.linalg.solve(A, b)
        s, t = float(sol[0]), float(sol[1])
        pt = pA + s * vA
        return True, pt, s, t, cond

