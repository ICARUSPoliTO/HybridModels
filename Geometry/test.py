            # ignora la traslazione dei due lati i e ip1:
            # effettua l'intersezione tra i lati "prima" e "dopo" quelli considerati:
            if (lenA <= Lmin) & (lenB <= Lmin):
                im = (i - 1) % n
                ip2 = (ip1 + 1) % n
