D_casing = 26.5e-3  # [m] = 26.5 mm

r_interno = D_int_base / 2  # 3.31 mm
r_esterno = D_ext / 2  # 10.0 mm
r_casing = D_casing / 2  # 13.25 mm

# Numero di lobi
n_lobi = 10

